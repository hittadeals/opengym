#!/usr/bin/env node
// Build the id -> 360x360 GIF map from ExerciseGymGifsDB (free, static, jsDelivr).
//
// Why this source: it is the same Gym visual animation set as the bundled 180x180 media
// (verified frame-for-frame on a sample), just at 360x360. The exercise names line up
// almost one-to-one, so a strict name match is enough to keep every demo correct.
//
// Matching is deliberately conservative:
//   1. exact token-set match after normalisation -> mapped
//   2. our "v. 2"/"v. 3" variant with no counterpart -> the base exercise, marked as a
//      variant in the report (the movement is the same, the rendition may differ)
//   3. anything else stays unmapped and keeps the local 180 GIF
//
// Usage:
//   node scripts/build-hd-map.mjs                 # fetch the pinned index and write the map
//   node scripts/build-hd-map.mjs --index file.json
//
// The generated file is committed so the app does not depend on this script at runtime.
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { EXDB } from '../frontend/src/lib/exercises-data.js'

const here = path.dirname(fileURLToPath(import.meta.url))
const repo = path.resolve(here, '..')
const TAG = process.env.HD_TAG || 'v1.1.0'
const BASE = `https://cdn.jsdelivr.net/gh/JahelCuadrado/ExerciseGymGifsDB@${TAG}/`
const INDEX_URL = BASE + 'api/en/exercises.json'

const args = process.argv.slice(2)
const opt = (name, fallback) => {
  const i = args.indexOf('--' + name)
  return i >= 0 && args[i + 1] && !args[i + 1].startsWith('--') ? args[i + 1] : fallback
}
const out = path.resolve(opt('out', path.join(repo, 'frontend', 'src', 'lib', 'hd-media.js')))

const STOP = new Set(['a', 'an', 'the', 'with', 'and', 'or', 'on', 'to', 'of', 'from', 'in', 'at', 'for', 'male', 'female', 'position', 'degree'])

// Mojibake from the upstream JSON ("45в°", "45â°") and typographic degree signs are all
// the same thing; dropping the word "degree" makes "45° side bend" match "45 Side Bend".
const tokens = s => String(s || '')
  .replace(/[âã]°|в°/g, ' ')
  .replace(/[°º]/g, ' ')
  .toLowerCase()
  .replace(/\bv\s*\.?\s*(\d+)\b/g, 'v$1')
  .replace(/[^a-z0-9]+/g, ' ')
  .split(/\s+/)
  .filter(w => w && !STOP.has(w))
const key = s => [...new Set(tokens(s))].sort().join(' ')
const stripVersion = s => tokens(s).filter(w => !/^v\d+$/.test(w)).join(' ')

async function loadIndex () {
  const file = opt('index')
  if (file) return JSON.parse(fs.readFileSync(path.resolve(file), 'utf8'))
  const res = await fetch(INDEX_URL)
  if (!res.ok) throw new Error(`Could not fetch ${INDEX_URL}: HTTP ${res.status}`)
  return res.json()
}

const json = await loadIndex()
const docs = Array.isArray(json) ? json : json.exercises
if (!Array.isArray(docs) || !docs.length) throw new Error('No exercises in index')

const byName = new Map()
for (const d of docs) {
  if (!byName.has(key(d.name))) byName.set(key(d.name), d)
}

const map = {}
const variants = []
const unmatched = []
for (const ex of EXDB) {
  const k = key(ex.n)
  let hit = byName.get(k)
  if (hit) { map[ex.id] = hit.file; continue }
  const base = stripVersion(ex.n)
  if (base && base !== tokens(ex.n).join(' ')) {
    hit = byName.get(key(base))
    if (hit) { map[ex.id] = hit.file; variants.push(`${ex.id} ${ex.n} -> ${hit.name}`); continue }
  }
  unmatched.push(`${ex.id} ${ex.n}`)
}

const lines = [
  '// Generated by scripts/build-hd-map.mjs — do not edit by hand.',
  '//',
  '// 360x360 exercise GIFs from JahelCuadrado/ExerciseGymGifsDB, served through jsDelivr.',
  '// The media belongs to its respective authors (see NOTICE.md); the app falls back to',
  '// the bundled 180x180 file for any id that is missing here.',
  `export const HD_TAG = ${JSON.stringify(TAG)}`,
  `export const HD_BASE = ${JSON.stringify(BASE)}`,
  'export const HD_GIF = ' + JSON.stringify(map) + '\n'
]
fs.writeFileSync(out, lines.join('\n'), 'utf8')

console.log(`index:    ${docs.length} exercises`)
console.log(`ours:     ${EXDB.length}`)
console.log(`mapped:   ${Object.keys(map).length}`)
console.log(`variants: ${variants.length} (v.2/v.3 -> base rendition)`)
console.log(`unmapped: ${unmatched.length} (kept the 180 GIF)`)
if (unmatched.length) console.log(unmatched.join('\n'))
console.log(`\nwrote ${path.relative(repo, out)}`)
